import { expect, test } from '@playwright/test';
import type { Page, TestInfo } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { unzipSync, strFromU8 } from 'fflate';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

const toolbar = '[data-scope]';
const button = (page: Page, format: 'PDF' | 'EPUB') =>
  page.getByRole('button', { name: `${format} 다운로드`, exact: true });

async function convert(
  page: Page,
  input: string | { name: string; mimeType: string; buffer: Buffer },
) {
  await page.locator('#pdf-file-input').setInputFiles(input);
  await expect(page.locator(toolbar)).toHaveAttribute('data-scope', 'preview', { timeout: 60_000 });
  await expect(page.getByRole('button', { name: '변환', exact: true })).toBeEnabled();
  await expect(button(page, 'PDF')).toBeDisabled();
  await expect(button(page, 'EPUB')).toBeDisabled();
  await page.getByRole('button', { name: '변환', exact: true }).click();
  await expect(page.locator(toolbar)).toHaveAttribute('data-scope', 'full', { timeout: 60_000 });
  await expect(button(page, 'PDF')).toBeEnabled();
  await expect(button(page, 'EPUB')).toBeEnabled();
  await expect(page.locator('.error-message')).toHaveCount(0);
}

async function download(page: Page, info: TestInfo, format: 'PDF' | 'EPUB') {
  const pending = page.waitForEvent('download');
  await button(page, format).click();
  const file = await pending;
  const path = info.outputPath(file.suggestedFilename());
  await file.saveAs(path);
  expect(await file.failure()).toBeNull();
  return { name: file.suggestedFilename(), bytes: await readFile(path) };
}

/** Check the actual downloaded publication, including links generated by the worker. */
async function inspectEpub(page: Page, bytes: Buffer) {
  const files = unzipSync(bytes);
  const filenameLength = bytes.readUInt16LE(26);
  expect(bytes.toString('ascii', 30, 30 + filenameLength)).toBe('mimetype');
  expect(bytes.readUInt16LE(8)).toBe(0);
  expect(bytes.readUInt16LE(28)).toBe(0);
  expect(strFromU8(files.mimetype)).toBe('application/epub+zip');
  const xml = Object.fromEntries(
    Object.entries(files)
      .filter(([path]) => /\.(?:xml|xhtml|opf|ncx)$/u.test(path))
      .map(([path, data]) => [path, strFromU8(data)]),
  );
  const publication = await page.evaluate((documents) => {
    const parsed = new Map(
      Object.entries(documents).map(([path, source]) => [
        path,
        new DOMParser().parseFromString(source, 'application/xml'),
      ]),
    );
    const failures = [...parsed].flatMap(([path, document]) =>
      document.querySelector('parsererror') ? [path] : [],
    );
    if (failures.length) throw new Error(`Invalid XML: ${failures.join(', ')}`);
    const container = parsed.get('META-INF/container.xml')!;
    const packagePath = container
      .getElementsByTagNameNS('*', 'rootfile')[0]
      ?.getAttribute('full-path');
    if (!packagePath) throw new Error('The EPUB container does not identify its package document.');
    const document = parsed.get(packagePath)!;
    const items = [...document.getElementsByTagNameNS('*', 'item')].map((item) => ({
      id: item.getAttribute('id')!,
      href: item.getAttribute('href')!,
      type: item.getAttribute('media-type')!,
      properties: (item.getAttribute('properties') ?? '').split(/\s+/u),
    }));
    const resolveFile = (from: string, href: string) => {
      const url = new URL(href, `https://epub.invalid/${from}`);
      return {
        path: decodeURIComponent(url.pathname.slice(1)),
        fragment: decodeURIComponent(url.hash.slice(1)),
      };
    };
    const spine = [...document.getElementsByTagNameNS('*', 'itemref')].map((item) => {
      const manifest = items.find((entry) => entry.id === item.getAttribute('idref'));
      if (!manifest) throw new Error('A spine item is absent from the manifest.');
      return resolveFile(packagePath, manifest.href).path;
    });
    const nav = items.filter((item) => item.properties.includes('nav'));
    const navDocument = nav[0] && parsed.get(resolveFile(packagePath, nav[0].href).path);
    const toc =
      navDocument &&
      [...navDocument.getElementsByTagNameNS('*', 'nav')].filter((element) =>
        (element.getAttributeNS('http://www.idpf.org/2007/ops', 'type') ?? '')
          .split(/\s+/u)
          .includes('toc'),
      );
    const references = [...parsed].flatMap(([path, entry]) =>
      [...entry.querySelectorAll('[href], [src]')].flatMap((element) => {
        const href = element.getAttribute('src') ?? element.getAttribute('href') ?? '';
        if (!href || /^[a-z]+:/iu.test(href)) return [];
        return [{ from: path, ...resolveFile(path, href) }];
      }),
    );
    const spineDocuments = spine.map((path) => {
      const entry = parsed.get(path);
      if (!entry) throw new Error(`Missing content document: ${path}`);
      return entry;
    });
    return {
      packageNamespace: document.documentElement.namespaceURI,
      title: document.getElementsByTagNameNS('http://purl.org/dc/elements/1.1/', 'title')[0]
        ?.textContent,
      language: document.getElementsByTagNameNS('http://purl.org/dc/elements/1.1/', 'language')[0]
        ?.textContent,
      manifest: items.map((item) => ({ ...item, path: resolveFile(packagePath, item.href).path })),
      spine,
      navCount: nav.length,
      tocCount: toc?.length ?? 0,
      references,
      ids: Object.fromEntries(
        [...parsed].map(([path, entry]) => [
          path,
          [...entry.querySelectorAll('[id]')].map((element) => element.id),
        ]),
      ),
      text: spineDocuments
        .map((entry) => entry.getElementsByTagNameNS('*', 'body')[0]?.textContent ?? '')
        .join(' '),
      inlineImages: spineDocuments.flatMap((entry) =>
        [...entry.getElementsByTagNameNS('*', 'img')]
          .filter((image) => {
            const paragraph = image.closest('p');
            return paragraph && (paragraph.textContent?.trim().length ?? 0) > 20;
          })
          .map((image) => ({
            src: image.getAttribute('src'),
            style: image.getAttribute('style') ?? '',
            className: image.getAttribute('class') ?? '',
          })),
      ),
    };
  }, xml);
  expect(publication.packageNamespace).toBe('http://www.idpf.org/2007/opf');
  expect(publication.title?.trim()).toBeTruthy();
  expect(publication.language?.trim()).toMatch(/^[a-z]{2,3}(?:-[a-zA-Z0-9]+)*$/u);
  expect(publication.spine.length).toBeGreaterThan(0);
  expect(publication.navCount).toBe(1);
  expect(publication.tocCount).toBe(1);
  for (const item of publication.manifest) expect(files[item.path], item.path).toBeDefined();
  for (const reference of publication.references) {
    expect(files[reference.path], `${reference.from} -> ${reference.path}`).toBeDefined();
    if (reference.fragment)
      expect(publication.ids[reference.path], reference.path).toContain(reference.fragment);
  }
  for (const [path, data] of Object.entries(files).filter(([path]) => path.endsWith('.css'))) {
    for (const match of strFromU8(data).matchAll(/url\(\s*['"]?([^'")\s]+)['"]?\s*\)/gu)) {
      const target = new URL(match[1], `https://epub.invalid/${path}`);
      expect(target.origin, path).toBe('https://epub.invalid');
      expect(
        files[decodeURIComponent(target.pathname.slice(1))],
        `${path} -> ${target.pathname}`,
      ).toBeDefined();
    }
  }
  for (const [path, data] of Object.entries(files).filter(([path]) => path.endsWith('.png'))) {
    expect([...data.subarray(0, 8)], path).toEqual([137, 80, 78, 71, 13, 10, 26, 10]);
    expect(data.length, path).toBeGreaterThan(100);
  }
  return { ...publication, files };
}

test('one full conversion offers PDF and a self-contained reflowable EPUB', async ({
  page,
}, info) => {
  await page.goto('');
  await convert(page, resolve('.cache/fixtures/mixed-document.pdf'));
  const pdf = await download(page, info, 'PDF');
  expect(pdf.name).toBe('mixed-document-formatted.pdf');
  expect((await PDFDocument.load(pdf.bytes)).getPageCount()).toBeGreaterThan(0);
  const epub = await download(page, info, 'EPUB');
  expect(epub.name).toBe('mixed-document-formatted.epub');
  const publication = await inspectEpub(page, epub.bytes);
  const text = publication.text.replace(/\s+/gu, ' ').trim();
  expect(text).toContain('This document was written specifically for testing PDF reflow.');
  expect(text).toContain('한글 문단의 줄바꿈');
  expect(text).toContain('A small footnote remains part of the source and must not disappear.');
  expect(text.indexOf('Left column begins here.')).toBeGreaterThanOrEqual(0);
  expect(text.indexOf('Right column begins here.')).toBeGreaterThan(
    text.indexOf('after layout changes.'),
  );
  expect(
    Object.keys(publication.files).filter((path) => path.endsWith('.png')).length,
  ).toBeGreaterThanOrEqual(3);
  await expect(button(page, 'PDF')).toBeEnabled();
  await expect(button(page, 'EPUB')).toBeEnabled();
  await page.getByLabel('위 여백', { exact: true }).fill('15');
  await expect(page.locator(toolbar)).toHaveAttribute('data-stale', 'true');
  await expect(button(page, 'PDF')).toBeDisabled();
  await expect(button(page, 'EPUB')).toBeDisabled();
});

test('EPUB retains inline formula geometry and an image-only source page', async ({
  page,
}, info) => {
  await page.goto('');
  const scan = await page.evaluate(() => {
    const canvas = document.createElement('canvas');
    canvas.width = 400;
    canvas.height = 600;
    const context = canvas.getContext('2d')!;
    context.fillStyle = '#ffffff';
    context.fillRect(0, 0, 400, 600);
    context.fillStyle = '#202020';
    context.font = '24px sans-serif';
    context.fillText('Synthetic scanned page', 30, 70);
    context.fillRect(30, 130, 180, 250);
    return canvas.toDataURL('image/png').split(',')[1];
  });
  const source = await PDFDocument.create();
  const font = await source.embedFont(StandardFonts.Helvetica);
  const first = source.addPage([612, 792]);
  const prefix = 'The coefficient of determination (R';
  const x = 48,
    y = 690,
    size = 12;
  first.drawText(prefix, { x, y, size, font });
  const exponentX = x + font.widthOfTextAtSize(prefix, size);
  first.drawText('2', { x: exponentX, y: y + 4, size: 8, font });
  first.drawText(') remains embedded in this ordinary prose sentence.', {
    x: exponentX + font.widthOfTextAtSize('2', 8),
    y,
    size,
    font,
  });
  first.drawText('The following sentence must remain searchable text.', { x, y: 668, size, font });
  first.drawRectangle({ x: 100, y: 400, width: 280, height: 100, color: rgb(0.1, 0.3, 0.7) });
  const image = await source.embedPng(Buffer.from(scan, 'base64'));
  source.addPage([400, 600]).drawImage(image, { x: 0, y: 0, width: 400, height: 600 });
  await convert(page, {
    name: 'inline-and-scan.pdf',
    mimeType: 'application/pdf',
    buffer: Buffer.from(await source.save()),
  });
  const downloaded = await download(page, info, 'EPUB');
  expect(downloaded.name).toBe('inline-and-scan-formatted.epub');
  const publication = await inspectEpub(page, downloaded.bytes);
  expect(publication.text).toContain('The coefficient of determination');
  expect(publication.text).toContain('The following sentence must remain searchable text.');
  expect(publication.text).not.toContain('Synthetic scanned page');
  expect(publication.inlineImages.length).toBeGreaterThan(0);
  const pngs = Object.values(publication.files).filter(
    (data) => data[0] === 137 && data[1] === 80 && data[2] === 78,
  );
  const scannedPage = pngs.find((data) => {
    const view = new DataView(data.buffer, data.byteOffset, data.byteLength);
    return view.getUint32(16) >= 400 && view.getUint32(20) >= 600;
  });
  expect(scannedPage).toBeDefined();
  const darkPixels = await page.evaluate(
    async (bytes) => {
      const image = await createImageBitmap(
        new Blob([new Uint8Array(bytes)], { type: 'image/png' }),
      );
      const canvas = document.createElement('canvas');
      canvas.width = image.width;
      canvas.height = image.height;
      const context = canvas.getContext('2d')!;
      context.drawImage(image, 0, 0);
      image.close();
      const pixels = context.getImageData(0, 0, canvas.width, canvas.height).data;
      let dark = 0;
      for (let offset = 0; offset < pixels.length; offset += 4)
        if (
          pixels[offset + 3] > 200 &&
          pixels[offset] < 140 &&
          pixels[offset + 1] < 140 &&
          pixels[offset + 2] < 140
        )
          dark++;
      return dark;
    },
    [...scannedPage!],
  );
  expect(darkPixels).toBeGreaterThan(1000);
});
